import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve, relative } from 'node:path';
import { homedir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { coordinatorStatus } from '../../../../subs/harness/subs/assistance/src/coordinator-client.ts';
const evidence = resolve('plans/codex-coordinator-host/iteration-03/live-qualification');
const target = JSON.parse(await readFile(join(evidence, 'pilot-target.json'), 'utf8'));
const status = await coordinatorStatus(target.root);
const request = status.record.pending.find(request => request.itemId === process.argv[2] && request.kind === 'file-approval');
if (!request) throw new Error('Exact pending file request required');
const label = process.argv[3];
if (!label || !/^[a-z0-9-]+$/.test(label)) throw new Error('Safe artifact label required');
const histories = execFileSync('rg', ['--files', join(process.env.CODEX_HOME ?? join(homedir(), '.codex'), 'sessions')], { encoding: 'utf8' }).trim().split('\n');
const history = histories.find(path => path.includes(request.threadId));
if (!history) throw new Error('Native history for exact requesting thread is unavailable');
const calls = (await readFile(history, 'utf8')).split('\n').filter(Boolean).map(line => JSON.parse(line)).filter(row => row.type === 'response_item' && row.payload.type === 'custom_tool_call' && row.payload.name === 'exec' && row.payload.input.includes('tools.apply_patch('));
const call = calls.at(-1)?.payload;
const literal = call?.input.match(/tools\.apply_patch\(("(?:\\.|[^"\\])*")\)/)?.[1] ?? call?.input.match(/\bconst patch\s*=\s*("(?:\\.|[^"\\])*")\s*;/)?.[1];
if (!literal) throw new Error('No exact plain apply_patch literal is available for inspection');
const patch = JSON.parse(literal);
const paths = [...patch.matchAll(/^\*\*\* (?:Update|Add|Delete) File: (.+)$/gm)].map(match => match[1]);
if (!paths.length || paths.some(path => relative(target.root, resolve(path)).startsWith('..') || !relative(target.root, resolve(path)).startsWith('src/'))) throw new Error('Patch extends beyond this pilot source');
const inspection = { at: new Date().toISOString(), request, paths, patchSha256: createHash('sha256').update(patch).digest('hex'), nativeHistory: history, nativeCallId: call.call_id, authority: 'Operator inspects the retained exact captured-plan source/test patch before once-only approval.' };
await writeFile(join(evidence, `${label}.patch`), patch + '\n');
await writeFile(join(evidence, `${label}.json`), JSON.stringify(inspection, null, 2) + '\n');
console.log(patch);
console.log(JSON.stringify({ inspectionFile: `${label}.json`, paths, patchSha256: inspection.patchSha256 }));
